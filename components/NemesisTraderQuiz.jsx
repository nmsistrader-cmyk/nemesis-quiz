function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function freshDeckAvoidingRepeat(poolLength, avoidPoolIndex) {
  const deck = shuffle(Array.from({ length: poolLength }, (_, i) => i));
  if (poolLength > 1 && deck[0] === avoidPoolIndex) {
    const swapWith = 1 + Math.floor(Math.random() * (poolLength - 1));
    [deck[0], deck[swapWith]] = [deck[swapWith], deck[0]];
  }
  return deck;
}

